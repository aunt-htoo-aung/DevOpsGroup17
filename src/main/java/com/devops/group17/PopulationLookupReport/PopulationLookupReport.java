package com.devops.group17.PopulationLookupReport;

public class PopulationLookupReport {

    // For all options
    private String name;
    private String continent;
    private String region;
    private String country;
    private String district;
    private String city;
    private String countryCode;
    private long population;

    // ---------------------
    public String getName(){return name;}

    public void setName(String name){this.name = name;}

    public String getContinent(){return continent;}

    public void setContinent(String name){this.continent = continent;}

    public String getRegion(){return region;}

    public void setRegion(String name){this.region = region;}

    public String getCountry(){return country;}

    public void setCountry(String name){this.country = country;}

    public String getDistrict(){return district;}

    public void setDistrict(String name){this.district = district;}

    public String getCity(){return city;}

    public void setCity(String name){this.city = city;}

    public String getCountryCode(){return countryCode;}

    public void setCountryCode(String name){this.countryCode = countryCode;}

    public long getPopulation(){return population;}

    public void setPopulation(long population){this.population = population;}

}